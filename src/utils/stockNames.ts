export function getTWName(symbol: string): string | undefined {
  const code = symbol.replace(/\.TWO?$/i, '');
  return TW_STOCK_NAMES[code];
}

export interface StockSuggestion {
  code: string;
  name: string;
}

export function searchStocks(query: string): StockSuggestion[] {
  if (!query.trim()) return [];
  const q = query.trim().toLowerCase();
  const results: StockSuggestion[] = [];
  const seen = new Set<string>();
  for (const [code, name] of Object.entries(TW_STOCK_NAMES)) {
    if (seen.has(code)) continue;
    seen.add(code);
    if (code.startsWith(q) || name.includes(q)) {
      results.push({ code, name });
    }
  }
  return results.slice(0, 8);
}

/** Returns true if string contains Chinese characters */
export function hasChinese(s: string): boolean {
  return /[一-鿿]/.test(s);
}
